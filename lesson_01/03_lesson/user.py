class User:
    def __init__(salf, first_name, last_name):
        salf.first_name = first_name
        salf.last_name = last_name
    def get_first_name(salf):
        return salf.first_name
    def get_last_name(salf):
        return salf.last_name
    def get_first_last_name(salf):
        return f"{salf.first_name} {salf.last_name}" 